// cliDir writes an agent config for e into a fresh directory and returns it.
func cliDir(t *testing.T, e *emulator) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "cli")
	os.MkdirAll(dir, 0o755)
	if err := os.WriteFile(filepath.Join(dir, "orderecho.yaml"), []byte(fmt.Sprintf(agentConfig, e.fixPort, e.strictPort)), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

type cliRun struct {
	code int
	out  string
}

func runCLI(t *testing.T, dir string, timeout time.Duration, args ...string) cliRun {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, agentBin, append([]string{"--config", "orderecho.yaml"}, args...)...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	code := 0
	if err != nil {
		var ee *exec.ExitError
		if !asExitError(err, &ee) {
			t.Fatalf("running CLI: %v\n%s", err, out)
		}
		code = ee.ExitCode()
	}
	if ctx.Err() != nil {
		t.Fatalf("CLI timed out:\n%s", out)
	}
	t.Logf("$ orderecho %s  -> exit %d\n%s", strings.Join(args, " "), code, out)
	return cliRun{code: code, out: string(out)}
}

func asExitError(err error, target **exec.ExitError) bool {
	e, ok := err.(*exec.ExitError)
	if ok {
		*target = e
	}
	return ok
}
