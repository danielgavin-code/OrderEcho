func startEmulator(t *testing.T) *emulator {
	t.Helper()
	requireEmulator(t)
	e := &emulator{t: t, dir: filepath.Join(t.TempDir(), "emulator"), out: &lockedBuffer{}}
	e.fixPort, e.strictPort, e.apiPort = freePort(t), freePort(t), freePort(t)
	for e.strictPort == e.fixPort || e.apiPort == e.fixPort || e.apiPort == e.strictPort {
		e.strictPort, e.apiPort = freePort(t), freePort(t)
	}
	os.MkdirAll(e.dir, 0o755)
	cfgPath := filepath.Join(e.dir, "emulator.yaml")
	cfg := fmt.Sprintf(emulatorConfig, e.fixPort, e.strictPort,
		filepath.Join(e.dir, "data", "seqnums"), filepath.Join(e.dir, "data", "evidence"),
		filepath.Join(e.dir, "data", "msgstore"), filepath.Join(e.dir, "logs"), e.apiPort)
	if err := os.WriteFile(cfgPath, []byte(cfg), 0o644); err != nil {
		t.Fatal(err)
	}
	e.cmd = exec.Command(pythonBin, filepath.Join(emulatorDir, "orderecho_Main.py"), "--config", cfgPath)
	e.cmd.Dir = e.dir // relative paths never land in the emulator's folder
	// No .pyc writes into the emulator's folder.
	e.cmd.Env = append(os.Environ(), "PYTHONDONTWRITEBYTECODE=1", "PYTHONUNBUFFERED=1")
	e.cmd.Stdout, e.cmd.Stderr = e.out, e.out
	if err := e.cmd.Start(); err != nil {
		t.Fatalf("starting emulator: %v", err)
	}
	exited := make(chan struct{})
	go func() { e.cmd.Wait(); close(exited) }()
	t.Cleanup(func() {
		e.cmd.Process.Signal(syscall.SIGTERM)
		select {
		case <-exited:
		case <-time.After(15 * time.Second):
			e.cmd.Process.Kill()
			<-exited
		}
		if t.Failed() {
			t.Logf("emulator output:\n%s", e.out.String())
			for _, p := range globAll(filepath.Join(e.dir, "logs", "engine", "*.log")) {
				data, _ := os.ReadFile(p)
				t.Logf("emulator engine log %s:\n%s", p, data)
			}
		}
	})
	deadline := time.Now().Add(30 * time.Second)
	for {
		select {
		case <-exited:
			t.Fatalf("emulator exited during startup:\n%s", e.out.String())
		default:
		}
		resp, err := httpClient.Get(e.url("/health"))
		if err == nil {
			resp.Body.Close()
			if resp.StatusCode == 200 {
				break
			}
		}
		if time.Now().After(deadline) {
			t.Fatalf("emulator /health never answered:\n%s", e.out.String())
		}
		time.Sleep(100 * time.Millisecond)
	}
	t.Logf("emulator up: fix=%d strict=%d api=%d dir=%s", e.fixPort, e.strictPort, e.apiPort, e.dir)
	return e
}

func globAll(pattern string) []string { m, _ := filepath.Glob(pattern); return m }

// httpClient never keeps connections alive, so the emulator's HTTP server can
// shut down at once.
var httpClient = &http.Client{Timeout: 10 * time.Second, Transport: &http.Transport{DisableKeepAlives: true}}

func (e *emulator) url(path string) string {
	return fmt.Sprintf("http://127.0.0.1:%d%s", e.apiPort, path)
}

func (e *emulator) post(path string, body any) map[string]any {
	e.t.Helper()
	var r io.Reader = strings.NewReader("{}")
	if body != nil {
		data, _ := json.Marshal(body)
		r = bytes.NewReader(data)
	}
	resp, err := httpClient.Post(e.url(path), "application/json", r)
	if err != nil {
		e.t.Fatalf("POST %s: %v", path, err)
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != 200 {
		e.t.Fatalf("POST %s -> %d %s", path, resp.StatusCode, data)
	}
	var out map[string]any
	json.Unmarshal(data, &out)
	e.t.Logf("POST %s -> %s", path, strings.TrimSpace(string(data)))
	return out
}

func (e *emulator) getJSON(path string, into any) {
	e.t.Helper()
	resp, err := httpClient.Get(e.url(path))
	if err != nil {
		e.t.Fatalf("GET %s: %v", path, err)
	}
	defer resp.Body.Close()
	json.NewDecoder(resp.Body).Decode(into)
}

type emuStatus struct {
	State            string `json:"state"`
	NextOut          int    `json:"next_out"`
	NextIn           int    `json:"next_in"`
	PendingTestReqID string `json:"pending_test_req_id"`
	FixLogPath       string `json:"fix_log_path"`
}

func (e *emulator) status(id string) emuStatus {
	e.t.Helper()
	resp, err := httpClient.Get(e.url("/sessions/" + id + "/status"))
	if err != nil {
		e.t.Fatalf("status: %v", err)
	}
	defer resp.Body.Close()
	var s emuStatus
	json.NewDecoder(resp.Body).Decode(&s)
	return s
}

func (e *emulator) fixLog(id string) string {
	var all []string
	for _, p := range globAll(filepath.Join(e.dir, "logs", "fix", id+"_*.log")) {
		data, _ := os.ReadFile(p)
		all = append(all, string(data))
	}
	return strings.Join(all, "")
}

// --------------------------------------------------------------- agent

type agentSpec struct {
	id, version, target string
	port                int
	reset, reconnect    bool
}

type agent struct {
	t      *testing.T
	dir    string
	id     string
	ini    *transport.Initiator
	res    chan transport.Result
	cancel context.CancelFunc
	ev     *evidence.Writer
	fixLog *logs.FixLog
	engine *logs.EngineLog
	ag     *oeagent.Agent
	events chan session.Evidence
	result *transport.Result
}

var runSeq struct {
	sync.Mutex
	n int
}

// uniqueRunID keeps ClOrdIDs unique across every agent one emulator sees.
func uniqueRunID(id string) string {
	runSeq.Lock()
	defer runSeq.Unlock()
	runSeq.n++
	return fmt.Sprintf("%s-%s%d", evidence.MakeRunID(time.Now()), strings.ReplaceAll(id, "-", ""), runSeq.n)
}

func startAgent(t *testing.T, spec agentSpec) *agent {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "agent-"+spec.id)
	a := &agent{t: t, dir: dir, id: spec.id, res: make(chan transport.Result, 1), events: make(chan session.Evidence, 4096)}
	cfg := &config.Config{
		Storage: config.Storage{SeqnumDir: filepath.Join(dir, "data", "seqnums"), MsgstoreDir: filepath.Join(dir, "data", "msgstore"),
			EvidenceDir: filepath.Join(dir, "data", "evidence")},
		Logging: config.Logging{LogDir: filepath.Join(dir, "logs"), FixDelimiter: "|", EngineLevel: "DEBUG"},
	}
	sc := config.Session{ID: spec.id, FixVersion: spec.version, SenderCompID: "AGENT", TargetCompID: spec.target,
		Host: "127.0.0.1", Port: spec.port, HeartbeatSec: 30, ResetOnLogon: spec.reset,
		Defaults: config.Defaults{LogonTimeoutSec: 10, LogoutTimeoutSec: 10, HeartbeatGracePct: 20,
			Reconnect: spec.reconnect, ReconnectIntervalSec: 0.5, HeartbeatMismatch: "warn",
			IncludeHandlInst: true, ClOrdIDPrefix: "IT"}}
	cfg.Sessions = []config.Session{sc}
	ag, err := oeagent.New(oeagent.Options{Config: cfg, Session: sc, Clock: clock.SystemClock{}, RunID: uniqueRunID(spec.id),
		Tick: 100 * time.Millisecond,
		OnEvidence: func(e session.Evidence) {
			select {
			case a.events <- e:
			default:
			}
		}})
	if err != nil {
		t.Fatal(err)
	}
	a.ag, a.ini, a.ev, a.fixLog, a.engine = ag, ag.Init, ag.Evidence, ag.FixLog, ag.EngineLog
	ctx, cancel := context.WithCancel(context.Background())
	a.cancel = cancel
	go func() { a.res <- ag.Run(ctx) }()
	t.Cleanup(func() {
		a.ini.Stop("test cleanup")
		cancel()
		a.wait(10 * time.Second)
		ag.Close()
		if t.Failed() {
			data, _ := os.ReadFile(a.fixLogPath())
			t.Logf("agent FIX log:\n%s", data)
			for _, p := range globAll(filepath.Join(dir, "logs", "engine", "*.log")) {
				data, _ := os.ReadFile(p)
				t.Logf("agent engine log:\n%s", data)
			}
		}
	})
	return a
}

func (a *agent) snap() transport.Snapshot { return a.ini.Snapshot() }

func (a *agent) fixLogPath() string {
	return a.fixLog.PathFor(time.Now())
}

func (a *agent) waitActive(timeout time.Duration, logons int) {
	a.t.Helper()
	waitFor(a.t, timeout, fmt.Sprintf("%s logon #%d", a.id, logons), func() bool {
		s := a.snap()
		return s.State == session.Active && s.Logons >= logons
	})
}

// wait returns Run's result (once), or fails after timeout.
func (a *agent) wait(timeout time.Duration) transport.Result {
	if a.result != nil {
		return *a.result
	}
	select {
	case r := <-a.res:
		a.result = &r
		return r
	case <-time.After(timeout):
		a.t.Fatalf("agent %s did not finish within %s", a.id, timeout)
	}
	return transport.Result{}
}

// testRequestRoundTrip sends a TestRequest and waits for its Heartbeat.
func (a *agent) testRequestRoundTrip() {
	a.t.Helper()
	id, err := a.ini.TestRequest()
	if err != nil {
		a.t.Fatalf("TestRequest: %v", err)
	}
	waitFor(a.t, 5*time.Second, "Heartbeat answering "+id, func() bool {
		return a.snap().PendingTestReqID == ""
	})
	data, _ := os.ReadFile(a.fixLogPath())
	if !strings.Contains(string(data), "|112="+id+"|") || !regexpIn(string(data), `IN\s+seq=\d+\s+35=0\s+.*\|112=`+id+`\|`) {
		a.t.Fatalf("no inbound Heartbeat with 112=%s in agent FIX log", id)
	}
	a.t.Logf("%s: TestRequest %s answered", a.id, id)
}

// inSync waits until both sides agree on the sequence numbers.
func inSync(t *testing.T, a *agent, e *emulator, emuID string) {
	t.Helper()
	var last string
	waitFor(t, 5*time.Second, "sequence numbers in sync", func() bool {
		s, es := a.snap(), e.status(emuID)
		last = fmt.Sprintf("agent next_out=%d next_in=%d / emulator next_in=%d next_out=%d (%s)", s.NextOut, s.NextIn, es.NextIn, es.NextOut, es.State)
		return es.State == "ACTIVE" && s.State == session.Active && s.NextOut == es.NextIn && s.NextIn == es.NextOut
	})
	t.Logf("in sync: %s", last)
}

