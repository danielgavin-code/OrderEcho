var (
	repoRoot    string
	emulatorDir string
	pythonBin   string
	agentBin    string // built once in TestMain
	skipReason  string
)

func TestMain(m *testing.M) {
	wd, _ := os.Getwd()
	repoRoot = findRepoRoot(wd)
	emulatorDir = filepath.Clean(filepath.Join(repoRoot, "..", "OrderEchoFixEmulator"))
	pythonBin = filepath.Join(emulatorDir, ".venv", "bin", "python")
	switch {
	case !exists(filepath.Join(emulatorDir, "orderecho_Main.py")):
		skipReason = "emulator not found at " + emulatorDir
	case !exists(pythonBin):
		skipReason = "emulator venv not found at " + pythonBin
	}
	code := 0
	if skipReason == "" {
		dir, err := os.MkdirTemp("", "orderecho-interop-bin")
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		agentBin = filepath.Join(dir, "orderecho")
		build := exec.Command("go", "build", "-o", agentBin, "./cmd/orderecho")
		build.Dir = repoRoot
		if out, err := build.CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "building agent: %v\n%s", err, out)
			os.Exit(1)
		}
		code = m.Run()
		printParitySummary()
		os.RemoveAll(dir)
	} else {
		code = m.Run()
	}
	os.Exit(code)
}

func findRepoRoot(dir string) string {
	for d := dir; ; d = filepath.Dir(d) {
		if exists(filepath.Join(d, "go.mod")) {
			return d
		}
		if filepath.Dir(d) == d {
			return dir
		}
	}
}

func exists(p string) bool { _, err := os.Stat(p); return err == nil }

func requireEmulator(t *testing.T) {
	t.Helper()
	if skipReason != "" {
		t.Skip("interop: " + skipReason)
	}
}

func freePort(t *testing.T) int {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer l.Close()
	return l.Addr().(*net.TCPAddr).Port
}

func waitFor(t *testing.T, timeout time.Duration, what string, cond func() bool) {
	t.Helper()
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		if cond() {
			return
		}
		time.Sleep(50 * time.Millisecond)
	}
	t.Fatalf("timed out after %s waiting for %s", timeout, what)
}

